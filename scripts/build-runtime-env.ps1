#!/usr/bin/env pwsh
# Generate the staging runtime environment file for /opt/edumatch/runtime/.env.
#
# The file is written locally and pushed to the instance over SSM as a
# base64 payload, so no secret is ever printed to the console, placed in a
# command line, or committed. Values come from the local .env, which is the
# operator's own file and is git-ignored.
#
# Usage: scripts/build-runtime-env.ps1 [-OutputPath <path>]
[CmdletBinding()]
param(
  # Join-Path with more than two segments is PowerShell 6+ only. Build the path
  # step by step so this runs unchanged on Windows PowerShell 5.1 as well, which
  # is the default shell on a stock Windows host.
  [string]$OutputPath = [IO.Path]::Combine($PSScriptRoot, '..', 'artifacts', 'runtime', 'staging.env')
)

$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
$envFile = Join-Path $root '.env'
if (-not (Test-Path $envFile)) { throw "Missing $envFile" }

$cfg = @{}
foreach ($line in Get-Content $envFile) {
  if ($line -match '^\s*([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*)$') { $cfg[$Matches[1]] = $Matches[2] }
}

function Get-B64([string]$key) {
  # The JWT keys are stored base64-encoded in .env because PEM is multi-line.
  $v = $cfg[$key]
  if (-not $v) { throw "Missing $key in .env" }
  return [Text.Encoding]::UTF8.GetString([Convert]::FromBase64String($v))
}

$required = @(
  'AUTH_DB_ROOT_PASSWORD', 'AUTH_DB_PASSWORD',
  'SCHOLARSHIP_DB_ROOT_PASSWORD', 'SCHOLARSHIP_DB_PASSWORD',
  'CHAT_DB_ROOT_PASSWORD', 'CHAT_DB_PASSWORD',
  'MATCHING_DB_PASSWORD', 'RABBITMQ_USERNAME', 'RABBITMQ_PASSWORD',
  'AWS_TLS_DOMAIN', 'AWS_MAX_SESSION_HOURS'
)
$missing = $required | Where-Object { -not $cfg[$_] }
if ($missing) { throw "Missing required values in .env: $($missing -join ', ')" }

# Derive every variable the *deployed* Compose demands instead of trusting the
# hardcoded list above. The release transform rewrites the audited source
# Compose (dropping shared-secret JWT vars in favour of mounted RSA keys), so
# only the generated release file reflects what the host will actually run.
# A `${VAR:?message}` reference makes `docker compose config` fail, which means
# a missing value would otherwise only surface mid-deploy.
$generatedCompose = Get-ChildItem -Path (Join-Path $root 'artifacts') -Recurse -Filter 'compose.yml' -ErrorAction SilentlyContinue |
  Where-Object { $_.FullName -match 'release' } | Select-Object -First 1
$composePath = if ($generatedCompose) { $generatedCompose.FullName } else { Join-Path $root 'edumatch' 'docker-compose.yml' }
$composeText = Get-Content $composePath -Raw
Write-Host "validating against: $composePath"
$requiredRefs = [regex]::Matches($composeText, '\$\{([A-Z_][A-Z0-9_]*):\?[^}]*\}') |
  ForEach-Object { $_.Groups[1].Value } | Sort-Object -Unique

$jwtPublic = Get-B64 'EDUMATCH_JWT_PUBLIC_KEY'
$jwtPrivate = Get-B64 'EDUMATCH_JWT_PRIVATE_KEY'
if ($jwtPublic -notmatch 'BEGIN PUBLIC KEY') { throw 'EDUMATCH_JWT_PUBLIC_KEY is not a PEM public key' }
if ($jwtPrivate -notmatch 'BEGIN PRIVATE KEY') { throw 'EDUMATCH_JWT_PRIVATE_KEY is not a PEM private key' }

# Compose reads this file. Values with newlines must be quoted; every other
# value is emitted verbatim because Compose performs no escaping.
function Quote([string]$value) {
  if ($value -match "`n") { return '"' + ($value -replace '"', '\"') + '"' }
  return $value
}

$lines = New-Object System.Collections.Generic.List[string]
$lines.Add('# Generated by scripts/build-runtime-env.ps1 - do not commit')
$lines.Add('# Consumed by docker compose --env-file on the staging host.')
$lines.Add('')
$lines.Add('# --- database credentials ---')
foreach ($k in @('AUTH_DB_ROOT_PASSWORD', 'AUTH_DB_PASSWORD', 'SCHOLARSHIP_DB_ROOT_PASSWORD',
    'SCHOLARSHIP_DB_PASSWORD', 'CHAT_DB_ROOT_PASSWORD', 'CHAT_DB_PASSWORD', 'MATCHING_DB_PASSWORD')) {
  $lines.Add("$k=$(Quote $cfg[$k])")
}
$lines.Add('')
$lines.Add('# --- message broker ---')
$lines.Add("RABBITMQ_USERNAME=$(Quote $cfg['RABBITMQ_USERNAME'])")
$lines.Add("RABBITMQ_PASSWORD=$(Quote $cfg['RABBITMQ_PASSWORD'])")
$lines.Add('')
$lines.Add('# --- RSA verification is enabled outside local; material is mounted as files ---')
$lines.Add('# Keys live in /opt/edumatch/secrets and are mounted read-only into each')
$lines.Add('# container at /run/secrets, so no PEM ever travels through this env file.')
$lines.Add('')
# auth-service declares spring.mail.username/password without defaults, so
# Spring fails to start when they are absent. EmailService.sendVerificationEmail
# has no caller in the audited source (verified by search), so no message is
# ever sent: mail authentication is explicitly disabled rather than pointed at
# a relay, and the flow is reported as not implemented instead of pretended.
$lines.Add('# --- JWT ---')
$lines.Add('# RS256 is enforced (*_JWT_REQUIRE_RSA=true) and the signing material is')
$lines.Add('# mounted from /opt/edumatch/secrets. No shared-secret value is provided:')
$lines.Add('# app.jwt.secret defaults to empty in the audited properties and is only')
$lines.Add('# read on the HS256 fallback path, which fails closed under require-rsa.')
$lines.Add('')
$lines.Add('# --- service-to-service auth ---')
$lines.Add('# /api/internal/** is guarded by ROLE_ADMIN/ROLE_SERVICE. A user token can')
$lines.Add('# never satisfy that guard, so chat-service obtains its own identity through')
$lines.Add('# the client-credentials exchange. Both services must share these values.')
$lines.Add("APP_SERVICE_AUTH_ENABLED=$(Quote $cfg['APP_SERVICE_AUTH_ENABLED'])")
$lines.Add("APP_SERVICE_AUTH_CLIENT_ID=$(Quote $cfg['APP_SERVICE_AUTH_CLIENT_ID'])")
$lines.Add("APP_SERVICE_AUTH_CLIENT_SECRET=$(Quote $cfg['APP_SERVICE_AUTH_CLIENT_SECRET'])")
$lines.Add('')
$lines.Add('# --- SMTP: no mail is sent by the audited source; auth disabled ---')
# EmailService.sendVerificationEmail has no caller, so nothing is ever sent.
# The mail health indicator is disabled rather than pointed at a relay or a
# local sink: a reachable fake SMTP would make the indicator green while
# proving nothing, and an unreachable one makes /actuator/health report 503.
# Disabling it states plainly that this dependency is not exercised.
$lines.Add('SPRING_MAIL_USERNAME=staging-no-mail')
$lines.Add('SPRING_MAIL_PASSWORD=staging-no-mail')
$lines.Add('SPRING_MAIL_SMTP_AUTH=false')
$lines.Add('SPRING_MAIL_SMTP_STARTTLS_ENABLE=false')
$lines.Add('SPRING_MAIL_HOST=127.0.0.1')
$lines.Add('SPRING_MAIL_PORT=2525')
$lines.Add('MANAGEMENT_HEALTH_MAIL_ENABLED=false')
$lines.Add('')
$lines.Add('# --- staging session controls ---')
$lines.Add("EDUMATCH_MAX_SESSION_HOURS=$(Quote $cfg['AWS_MAX_SESSION_HOURS'])")
$lines.Add("EDUMATCH_STAGING_HOSTNAME=$(Quote $cfg['AWS_TLS_DOMAIN'])")

# Every `${VAR:?}` the Compose file mentions must be present in what we wrote,
# or the deploy would fail at `docker compose config`.
$emitted = @{}
foreach ($line in $lines) {
  if ($line -match '^([A-Z_][A-Z0-9_]*)=(.*)$') { $emitted[$Matches[1]] = $Matches[2] }
}
$unresolved = $requiredRefs | Where-Object { -not $emitted.ContainsKey($_) }
if ($unresolved) { throw "Compose requires variables the generated env does not define: $($unresolved -join ', ')" }
Write-Host "compose-required variables satisfied: $($requiredRefs.Count)"

$dir = Split-Path -Parent $OutputPath
New-Item -ItemType Directory -Force -Path $dir | Out-Null
# LF endings: this file is consumed by a Linux shell.
[IO.File]::WriteAllText($OutputPath, (($lines -join "`n") + "`n"), [Text.UTF8Encoding]::new($false))

# Emit the key material as separate files for the read-only mounts. LF endings
# matter because the PEM is parsed by OpenSSL on Linux.
$secretDir = Join-Path $dir 'secrets'
New-Item -ItemType Directory -Force -Path $secretDir | Out-Null
$pubPath = Join-Path $secretDir 'jwt-public.pem'
$privPath = Join-Path $secretDir 'jwt-private.pem'
[IO.File]::WriteAllText($pubPath, (($jwtPublic -replace "`r`n", "`n").TrimEnd() + "`n"), [Text.UTF8Encoding]::new($false))
[IO.File]::WriteAllText($privPath, (($jwtPrivate -replace "`r`n", "`n").TrimEnd() + "`n"), [Text.UTF8Encoding]::new($false))

$sha = (Get-FileHash $OutputPath -Algorithm SHA256).Hash.ToLower()
$pubSha = (Get-FileHash $pubPath -Algorithm SHA256).Hash.ToLower()
Write-Host "Wrote $OutputPath"
Write-Host "sha256=$sha"
Write-Host "Wrote $pubPath"
Write-Host "public-key-sha256=$pubSha"
Write-Host "Wrote $privPath (private material not hashed to stdout)"
Write-Host "keys=$($lines.Count) (secret values not displayed)"
